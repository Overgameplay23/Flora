#!/usr/bin/env node
// Turns the in-app privacy policy and help pages (src/legal/privacy.json, src/legal/support.json) into standalone
// pages you can host anywhere (GitHub Pages, your own domain, Netlify...) and give App Store Connect as the
// Privacy Policy URL and the Support URL, and the App Privacy answers (src/legal/appPrivacy.json) into the sheet
// to copy into App Store Connect's App Privacy section.
//   node scripts/export-privacy.js        writes docs/legal/privacy-policy.html, docs/legal/support.html and
//                                         docs/store/app-privacy.md
// src/__tests__/privacyPolicy.test.ts and appPrivacy.test.ts fail when a page is older than its JSON.
// The contact email lives in privacy.json only; both pages show it once it is filled in.
const fs = require("node:fs");
const path = require("node:path");

const SOURCE = path.join(__dirname, "..", "src", "legal", "privacy.json");
const TARGET = path.join(__dirname, "..", "docs", "legal", "privacy-policy.html");
const SUPPORT_SOURCE = path.join(__dirname, "..", "src", "legal", "support.json");
const SUPPORT_TARGET = path.join(__dirname, "..", "docs", "legal", "support.html");
const LABEL_SOURCE = path.join(__dirname, "..", "src", "legal", "appPrivacy.json");
const LABEL_TARGET = path.join(__dirname, "..", "docs", "store", "app-privacy.md");

const escape = (text) =>
  String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function longDate(dateKey) {
  const [y, m, d] = String(dateKey).split("-").map(Number);
  const months = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
  return y && m && d ? `${d} ${months[m - 1]} ${y}` : String(dateKey);
}

function contactSection(email) {
  return email
    ? `  <section>\n    <h2>Questions or requests</h2>\n    <p><a href="mailto:${escape(email)}">${escape(email)}</a></p>\n  </section>\n`
    : "";
}

function page(title, body) {
  return `<!doctype html>
<!-- Generated by scripts/export-privacy.js from src/legal/*.json. Edit the JSON, then re-run the script. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Luna · ${escape(title)}</title>
<style>
  :root { color-scheme: light dark; --ink: #2b2420; --soft: #5d534c; --paper: #fbf6ef; --accent: #b4532a; }
  @media (prefers-color-scheme: dark) { :root { --ink: #f3ece4; --soft: #c9beb4; --paper: #1d1916; --accent: #f2b489; } }
  body { margin: 0; background: var(--paper); color: var(--soft); font: 17px/1.6 -apple-system, "Segoe UI", system-ui, sans-serif; }
  main { max-width: 680px; margin: 0 auto; padding: 40px 16px 64px; }
  h1, h2 { color: var(--ink); font-family: Georgia, "Times New Roman", serif; line-height: 1.25; }
  h1 { font-size: 34px; margin: 0 0 4px; }
  h2 { font-size: 22px; margin: 32px 0 8px; }
  .updated { font-size: 14px; margin: 0 0 20px; }
  ul { padding-left: 22px; }
  li { margin: 6px 0; }
  a { color: var(--accent); }
</style>
</head>
<body>
<main>
${body}</main>
</body>
</html>
`;
}

function renderPrivacyHtml(policy) {
  const sections = policy.sections
    .map((section) => {
      const paragraphs = (section.paragraphs || []).map((p) => `    <p>${escape(p)}</p>`).join("\n");
      const bullets = (section.bullets || []).length
        ? `    <ul>\n${section.bullets.map((b) => `      <li>${escape(b)}</li>`).join("\n")}\n    </ul>`
        : "";
      return [`  <section>`, `    <h2>${escape(section.heading)}</h2>`, paragraphs, bullets, `  </section>`].filter(Boolean).join("\n");
    })
    .join("\n");
  const body = `  <h1>${escape(policy.title)}</h1>
  <p class="updated">Updated ${escape(longDate(policy.updated))}</p>
  <p>${escape(policy.intro)}</p>
${sections}
${contactSection(policy.contactEmail)}`;
  return page(policy.title, body);
}

function renderSupportHtml(support, contactEmail) {
  const questions = support.questions
    .map((item) => `  <section>\n    <h2>${escape(item.q)}</h2>\n    <p>${escape(item.a)}</p>\n  </section>`)
    .join("\n");
  const body = `  <h1>${escape(support.title)}</h1>
  <p>${escape(support.intro)}</p>
${questions}
${contactSection(contactEmail)}  <p><a href="privacy-policy.html">Privacy policy</a></p>
`;
  return page(support.title, body);
}

const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

/** The answer sheet for App Store Connect > App Privacy, in the order the questionnaire asks. */
function renderAppPrivacyMarkdown(label) {
  const byCategory = [];
  for (const item of label.collected) {
    const group = byCategory.find((g) => g.category === item.category);
    if (group) group.types.push(item.type);
    else byCategory.push({ category: item.category, types: [item.type] });
  }
  const linked = byCategory.map((g) => g.category);
  const lines = [
    `# ${label.title}`,
    "",
    "<!-- Generated by scripts/export-privacy.js from src/legal/appPrivacy.json. Edit the JSON, then re-run the script. -->",
    "",
    `For Luna ${label.version}. Updated ${longDate(label.updated)}. Drafted from the code; src/__tests__/appPrivacy.test.ts fails`,
    "when the app starts keeping something this sheet does not declare.",
    "",
    "Where: App Store Connect > the app > App Privacy. The Privacy Policy URL asked for there is the hosted",
    "`docs/legal/privacy-policy.html` (LAUNCH.md item 2).",
    "",
    "## 1. Data collection",
    "",
    '"Do you or your third-party partners collect data from this app?"',
    "",
    `**${label.collectsData ? "Yes, we collect data from this app" : "No, we do not collect data from this app"}**`,
    "",
    "## 2. Tick these data types",
    "",
    ...byCategory.map((g) => `- **${g.category}**: ${g.types.join(", ")}`),
    "",
    "Leave every other type unticked (section 5 says why).",
    "",
    "## 3. Answer the same three questions for each type",
    "",
    "| Data type | Purposes to tick | Linked to the user? | Used for tracking? | What it is |",
    "|---|---|---|---|---|",
    ...label.collected.map(
      (item) =>
        `| ${cell(item.type)} | ${cell(item.purposes.join(", "))} | ${item.linked ? "Yes" : "No"} | ${item.tracking ? "Yes" : "No"} | ${cell(item.what)} |`
    ),
    "",
    "## 4. What the store page will show",
    "",
    `- **Data Used to Track You**: ${label.tracking ? "see section 3" : "none"}`,
    `- **Data Linked to You**: ${linked.join(", ")}`,
    "- **Data Not Linked to You**: none",
    "",
    "## 5. Not collected, and why",
    "",
    "| Data type | Why it is not ticked |",
    "|---|---|",
    ...label.notCollected.map((item) => `| ${cell(item.type)} | ${cell(item.why)} |`),
    "",
    "## 6. Where each piece lives",
    "",
    "| Where | Holds | What |",
    "|---|---|---|",
    `| Sign-in (Supabase Auth) | ${cell(label.sources.auth.types.join(", "))} | ${cell(label.sources.auth.note)} |`,
    ...[
      ["table", label.sources.tables],
      ["database function", label.sources.rpcs],
      ["server function", label.sources.functions],
      ["storage bucket", label.sources.buckets],
    ].flatMap(([kind, entries]) =>
      Object.entries(entries).map(([name, entry]) => `| \`${name}\` (${kind}) | ${cell(entry.types.join(", ") || "nothing personal")} | ${cell(entry.note)} |`)
    ),
    "",
    "## 7. Update the label when",
    "",
    ...label.updateWhen.map((line) => `- ${line}`),
    "",
  ];
  return lines.join("\n");
}

module.exports = {
  renderPrivacyHtml,
  renderSupportHtml,
  renderAppPrivacyMarkdown,
  SOURCE,
  TARGET,
  SUPPORT_SOURCE,
  SUPPORT_TARGET,
  LABEL_SOURCE,
  LABEL_TARGET,
};

if (require.main === module) {
  const policy = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  const support = JSON.parse(fs.readFileSync(SUPPORT_SOURCE, "utf8"));
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, renderPrivacyHtml(policy));
  fs.writeFileSync(SUPPORT_TARGET, renderSupportHtml(support, policy.contactEmail));
  const label = JSON.parse(fs.readFileSync(LABEL_SOURCE, "utf8"));
  fs.mkdirSync(path.dirname(LABEL_TARGET), { recursive: true });
  fs.writeFileSync(LABEL_TARGET, renderAppPrivacyMarkdown(label));
  const rel = (file) => path.relative(path.join(__dirname, ".."), file);
  console.log(`wrote ${rel(TARGET)}, ${rel(SUPPORT_TARGET)} and ${rel(LABEL_TARGET)}`);
}

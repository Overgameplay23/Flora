#!/usr/bin/env node
// Writes mobile/.env.local so the Expo client talks to the LOCAL Supabase stack.
// .env.local overrides .env in Expo's env loading and is gitignored (.env*.local); .env is never touched.
// The local anon key is the Supabase CLI's well-known development key, not a production secret,
// but it is still never printed here.
//
//   node local-backend/write-env-local.js             -> uses this machine's LAN IP (works for a phone on the same Wi-Fi)
//   node local-backend/write-env-local.js --localhost -> uses 127.0.0.1 (web / same machine only)
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const mobileRoot = path.resolve(__dirname, "..");
const useLocalhost = process.argv.includes("--localhost");

function readStatus() {
  const raw = execFileSync("supabase", ["status", "-o", "json", "--workdir", __dirname], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
    shell: process.platform === "win32",
  });
  return JSON.parse(raw.slice(raw.indexOf("{")));
}

function lanAddress() {
  const virtual = /vethernet|wsl|docker|virtualbox|vmware|hyper-v|loopback|tailscale|zerotier/i;
  const candidates = [];
  for (const [name, entries] of Object.entries(os.networkInterfaces())) {
    if (virtual.test(name)) continue;
    for (const entry of entries || []) {
      if (entry.family === "IPv4" && !entry.internal && !entry.address.startsWith("169.254.")) {
        candidates.push(entry.address);
      }
    }
  }
  return candidates[0] || null;
}

const status = readStatus();
const apiUrl = new URL(status.API_URL);
const anonKey = status.ANON_KEY;
if (!anonKey) {
  console.error("Could not read ANON_KEY from `supabase status`. Is the local stack running?");
  process.exit(1);
}

const host = useLocalhost ? "127.0.0.1" : lanAddress() || "127.0.0.1";
const url = `http://${host}:${apiUrl.port}`;

const lines = [
  "# Generated by local-backend/write-env-local.js. Points the app at the LOCAL Supabase stack.",
  "# Delete this file to fall back to .env.",
  `EXPO_PUBLIC_SUPABASE_URL=${url}`,
  `EXPO_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  "",
];
fs.writeFileSync(path.join(mobileRoot, ".env.local"), lines.join("\n"));
console.log(`.env.local written: EXPO_PUBLIC_SUPABASE_URL=${url} (anon key set, not shown)`);
if (!useLocalhost && host !== "127.0.0.1") {
  console.log("A phone on the same network can reach this stack if Windows Firewall allows inbound TCP " + apiUrl.port + ".");
}

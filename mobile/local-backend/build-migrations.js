#!/usr/bin/env node
// Builds local-backend/supabase/migrations/ from the project's existing SQL WITHOUT modifying it.
//
// Why: the Supabase CLI only applies supabase/migrations/<14-digit-timestamp>_name.sql. The files in
// mobile/supabase/migrations are named 2025_12_31_*.sql (the CLI would parse them as duplicate
// versions "2025"/"2026"), and the real bootstrap DDL lives outside migrations/ in supabase/schema_*.sql.
// This script copies each source file, in dependency order, to a correctly named migration and stamps
// it with its source path and SHA-256 so the mapping stays auditable. Re-run it after editing any source.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const mobileRoot = path.resolve(__dirname, "..");
const outDir = path.join(__dirname, "supabase", "migrations");

// [source path relative to mobile/, target migration file name]
const PLAN = [
  ["supabase/schema_mvp.sql", "20250101000000_bootstrap_schema_mvp.sql"],
  ["supabase/schema_tasks.sql", "20250101000100_bootstrap_schema_tasks.sql"],
  ["supabase/schema_seed_tasks.sql", "20250101000200_bootstrap_schema_seed_tasks.sql"],
  ["supabase/schema_garden.sql", "20250101000300_bootstrap_schema_garden.sql"],
  ["supabase/schema_pet_stylize.sql", "20250101000400_bootstrap_schema_pet_stylize.sql"],
  ["supabase/schema_daily_loop_v1.sql", "20250101000500_bootstrap_schema_daily_loop_v1.sql"],
  ["supabase/migrations/2025_12_31_stabilize_schema.sql", "20251231000100_stabilize_schema.sql"],
  ["supabase/migrations/2025_12_31_daily_loop_schema_fix.sql", "20251231000200_daily_loop_schema_fix.sql"],
  ["supabase/migrations/2026_01_01_checkins_date_fix.sql", "20260101000000_checkins_date_fix.sql"],
  ["supabase/migrations/2026_01_02_habits_created_at.sql", "20260102000000_habits_created_at.sql"],
  ["supabase/migrations/2026_02_05_pet_processing_status.sql", "20260205000000_pet_processing_status.sql"],
  ["supabase/migrations/2026_02_06_gentle_streaks_weekly_reflection.sql", "20260206000000_gentle_streaks_weekly_reflection.sql"],
  ["supabase/migrations/2026_02_17_pet_chat_usage.sql", "20260217000100_pet_chat_usage.sql"],
  ["supabase/migrations/2026_02_17_task_completion_atomic.sql", "20260217000200_task_completion_atomic.sql"],
  ["supabase/migrations/2026_02_22_retention_engine_v1.sql", "20260222000000_retention_engine_v1.sql"],
  ["supabase/migrations/2026_02_23_garden_upgrade_system.sql", "20260223000100_garden_upgrade_system.sql"],
  ["supabase/migrations/2026_02_23_pet_chat_quota_hotfix.sql", "20260223000200_pet_chat_quota_hotfix.sql"],
  ["supabase/migrations/2026_02_23_pet_name.sql", "20260223000300_pet_name.sql"],
  ["local-backend/sql/restoration_local_compat.sql", "20260917000000_restoration_local_compat.sql"],
  ["local-backend/sql/fix_complete_task_variable_conflict.sql", "20260917000100_fix_complete_task_variable_conflict.sql"],
  ["local-backend/sql/local_day_rpcs.sql", "20260924000000_local_day_rpcs.sql"],
];

fs.mkdirSync(outDir, { recursive: true });
for (const existing of fs.readdirSync(outDir)) {
  if (existing.endsWith(".sql")) fs.unlinkSync(path.join(outDir, existing));
}

for (const [source, target] of PLAN) {
  const sourcePath = path.join(mobileRoot, source);
  const sql = fs.readFileSync(sourcePath, "utf8").replace(/^﻿/, "");
  const sha = crypto.createHash("sha256").update(fs.readFileSync(sourcePath)).digest("hex");
  const header =
    `-- GENERATED by local-backend/build-migrations.js. Do not edit; edit the source and re-run.\n` +
    `-- source: ${source}\n` +
    `-- sha256: ${sha}\n\n`;
  fs.writeFileSync(path.join(outDir, target), header + sql);
  console.log(`${target}  <-  ${source}`);
}
console.log(`\n${PLAN.length} migrations written to ${path.relative(mobileRoot, outDir)}`);
